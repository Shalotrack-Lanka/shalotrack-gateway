-- Benchmark schema for test/load_test_fleet.py.
--
-- Same TABLES, COLUMN TYPES and INDEXES the gateway meets in production
-- (numeric coordinates, IX_GpsTrackings_DeviceId_EventTime, the unique
-- CurrentLocations.VehicleId) so write cost is realistic. Only the columns the
-- gateway reads or writes are included. NEVER run this against a production
-- database: test/bench_seed.py refuses to unless told otherwise.

CREATE TABLE IF NOT EXISTS "SetupShalotrackDevices" (
    "ImeiNumber"     TEXT PRIMARY KEY,
    "DeviceCategory" TEXT,
    "SimNumber"      TEXT,
    "Status"         TEXT
);

CREATE TABLE IF NOT EXISTS "GpsDevices" (
    "DeviceId"         UUID PRIMARY KEY,
    "ImeiNumber"       TEXT UNIQUE NOT NULL,
    "SimNumber"        TEXT,
    "DeviceModel"      TEXT,
    "ProtocolType"     TEXT,
    "ActivationStatus" INTEGER,
    "CreatedAt"        TIMESTAMPTZ,
    "UpdatedAt"        TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS "DeviceAssignments" (
    "AssignmentId" UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    "DeviceId"     UUID,
    "VehicleId"    UUID,
    "Status"       INTEGER
);
CREATE INDEX IF NOT EXISTS "IX_DeviceAssignments_DeviceId" ON "DeviceAssignments"("DeviceId");

CREATE TABLE IF NOT EXISTS "DeviceStatuses" (
    "StatusId"       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DeviceId"       UUID NOT NULL,
    "IsOnline"       BOOLEAN,
    "LastHeartbeat"  TIMESTAMPTZ,
    "LastSeen"       TIMESTAMPTZ,
    "GpsSignal"      INTEGER NOT NULL DEFAULT 0,
    "BatteryLevel"   INTEGER NOT NULL DEFAULT 0,
    "IgnitionStatus" BOOLEAN,
    "MovementStatus" BOOLEAN,
    "PowerStatus"    INTEGER NOT NULL DEFAULT 0,
    "UpdatedAt"      TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_DeviceStatuses_DeviceId" ON "DeviceStatuses"("DeviceId");

CREATE TABLE IF NOT EXISTS "GpsTrackings" (
    "TrackingId"  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DeviceId"    UUID NOT NULL,
    "Latitude"    NUMERIC,
    "Longitude"   NUMERIC,
    "Altitude"    NUMERIC,
    "Speed"       NUMERIC,
    "Heading"     NUMERIC,
    "Satellites"  INTEGER,
    "GpsAccuracy" NUMERIC,
    "EventTime"   TIMESTAMPTZ NOT NULL,
    "CreatedAt"   TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_GpsTrackings_DeviceId" ON "GpsTrackings"("DeviceId");
CREATE INDEX IF NOT EXISTS "IX_GpsTrackings_DeviceId_EventTime" ON "GpsTrackings"("DeviceId", "EventTime" DESC);

CREATE TABLE IF NOT EXISTS "CurrentLocations" (
    "DeviceId"       UUID PRIMARY KEY,
    "VehicleId"      UUID NOT NULL,
    "Latitude"       NUMERIC,
    "Longitude"      NUMERIC,
    "Speed"          NUMERIC,
    "Heading"        NUMERIC,
    "IgnitionStatus" BOOLEAN,
    "MovementStatus" BOOLEAN,
    "LastUpdate"     TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CurrentLocations_VehicleId" ON "CurrentLocations"("VehicleId");

CREATE TABLE IF NOT EXISTS "DeviceEvents" (
    "EventId"     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DeviceId"    UUID,
    "VehicleId"   UUID,
    "EventType"   TEXT,
    "Severity"    INTEGER,
    "Latitude"    NUMERIC,
    "Longitude"   NUMERIC,
    "RawPacketId" UUID,
    "Description" TEXT,
    "Metadata"    JSONB,
    "CreatedAt"   TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS "IX_DeviceEvents_DeviceId" ON "DeviceEvents"("DeviceId");

CREATE TABLE IF NOT EXISTS "RawPackets" (
    "PacketId"       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DeviceId"       UUID,
    "ProtocolNumber" TEXT,
    "RawHex"         TEXT,
    "PacketLength"   INTEGER,
    "ReceivedAt"     TIMESTAMPTZ,
    "Parsed"         BOOLEAN
);
CREATE INDEX IF NOT EXISTS "IX_RawPackets_DeviceId" ON "RawPackets"("DeviceId");
CREATE INDEX IF NOT EXISTS "IX_RawPackets_DeviceId_ReceivedAt" ON "RawPackets"("DeviceId", "ReceivedAt");

CREATE TABLE IF NOT EXISTS "CommandResponses" (
    "Id"          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DeviceId"    UUID,
    "Command"     TEXT,
    "RawResponse" TEXT,
    "ParsedData"  TEXT
);
