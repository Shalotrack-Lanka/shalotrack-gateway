"""
Runs the single-statement position write (services/tracking_service.save_location)
against a REAL PostgreSQL. Skipped unless TEST_DATABASE_URL is set, so the normal
suite stays DB-free.

    TEST_DATABASE_URL=postgresql://user:pass@127.0.0.1:5432/postgres \\
        python -m unittest discover -s test -p "test_location_write_sql.py" -v

Everything is created in a throw-away schema (gw_sql_test) that is dropped at
the end, so it is safe to point at a scratch database. NEVER point it at
production: it creates and drops a schema.

The tables mirror the EF Core migrations in shalotrack-api (types, NOT NULLs,
the unique DeviceStatuses.DeviceId index, the non-unique GpsTrackings
(DeviceId, EventTime DESC) index).
"""

import os
import sys
import unittest
from contextlib import asynccontextmanager
from datetime import datetime, timezone
from unittest.mock import patch

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

DSN = os.environ.get("TEST_DATABASE_URL")

DEV_ASSIGNED = "11111111-1111-1111-1111-111111111111"      # assigned, ignition ON in DeviceStatuses
DEV_UNASSIGNED = "22222222-2222-2222-2222-222222222222"    # no active assignment
DEV_NO_STATUS = "33333333-3333-3333-3333-333333333333"     # assigned, no DeviceStatuses row
VEHICLE = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa"
VEHICLE_2 = "bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb"

SCHEMA = """
DROP SCHEMA IF EXISTS gw_sql_test CASCADE;
CREATE SCHEMA gw_sql_test;
SET search_path = gw_sql_test;
CREATE TABLE "GpsDevices"("DeviceId" uuid PRIMARY KEY);
CREATE TABLE "Vehicles"("VehicleId" uuid PRIMARY KEY);
CREATE TABLE "DeviceAssignments"("AssignmentId" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "AssignedAt" timestamptz NOT NULL DEFAULT now(), "DeviceId" uuid NOT NULL, "RemovedAt" timestamptz,
  "Status" integer NOT NULL, "VehicleId" uuid NOT NULL);
CREATE TABLE "DeviceStatuses"("StatusId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "BatteryLevel" integer NOT NULL, "DeviceId" uuid NOT NULL REFERENCES "GpsDevices", "GpsSignal" integer NOT NULL,
  "IgnitionStatus" boolean NOT NULL, "IsOnline" boolean NOT NULL, "LastHeartbeat" timestamptz, "LastSeen" timestamptz,
  "MovementStatus" boolean NOT NULL, "PowerStatus" integer NOT NULL, "UpdatedAt" timestamptz NOT NULL);
CREATE UNIQUE INDEX "IX_DeviceStatuses_DeviceId" ON "DeviceStatuses"("DeviceId");
CREATE TABLE "GpsTrackings"("TrackingId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "DeviceId" uuid NOT NULL REFERENCES "GpsDevices" ON DELETE CASCADE, "Latitude" numeric NOT NULL,
  "Longitude" numeric NOT NULL, "Altitude" numeric, "Speed" numeric NOT NULL, "Heading" numeric NOT NULL,
  "Satellites" integer NOT NULL, "GpsAccuracy" numeric, "EventTime" timestamptz NOT NULL, "CreatedAt" timestamptz NOT NULL);
CREATE INDEX "IX_GpsTrackings_DeviceId_EventTime" ON "GpsTrackings"("DeviceId", "EventTime" DESC);
CREATE TABLE "CurrentLocations"("DeviceId" uuid PRIMARY KEY REFERENCES "GpsDevices" ON DELETE CASCADE,
  "VehicleId" uuid NOT NULL REFERENCES "Vehicles" ON DELETE CASCADE, "Latitude" numeric NOT NULL,
  "Longitude" numeric NOT NULL, "Speed" numeric NOT NULL, "Heading" numeric NOT NULL,
  "IgnitionStatus" boolean NOT NULL, "MovementStatus" boolean NOT NULL, "LastUpdate" timestamptz NOT NULL);
INSERT INTO "GpsDevices" VALUES ('%(a)s'),('%(u)s'),('%(n)s');
INSERT INTO "Vehicles" VALUES ('%(v)s'),('%(v2)s');
INSERT INTO "DeviceAssignments"("DeviceId","Status","VehicleId") VALUES
  ('%(a)s',1,'%(v)s'), ('%(n)s',1,'%(v2)s'),
  ('%(u)s',0,'%(v)s');                                   -- Status 0 = not active
INSERT INTO "DeviceStatuses"("BatteryLevel","DeviceId","GpsSignal","IgnitionStatus","IsOnline","MovementStatus","PowerStatus","UpdatedAt")
  VALUES (6,'%(a)s',4,true,true,true,0,now());
""" % {"a": DEV_ASSIGNED, "u": DEV_UNASSIGNED, "n": DEV_NO_STATUS, "v": VEHICLE, "v2": VEHICLE_2}

T1 = datetime(2026, 11, 6, 15, 21, 27, tzinfo=timezone.utc)
T2 = datetime(2026, 11, 6, 15, 21, 49, tzinfo=timezone.utc)


@unittest.skipUnless(DSN, "set TEST_DATABASE_URL to run the SQL integration tests")
class SaveLocationSqlTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        import asyncpg
        from services import tracking_service
        self.ts = tracking_service
        self.conn = await asyncpg.connect(DSN, statement_cache_size=0)   # same setting as the real pool
        await self.conn.execute(SCHEMA)                                  # also sets search_path for this session
        self.addAsyncCleanup(self._drop)

        conn = self.conn

        @asynccontextmanager
        async def fake_managed_connection():
            yield conn

        patcher = patch.object(tracking_service, "managed_connection", fake_managed_connection)
        patcher.start()
        self.addCleanup(patcher.stop)

    async def _drop(self):
        await self.conn.execute("DROP SCHEMA IF EXISTS gw_sql_test CASCADE")
        await self.conn.close()

    async def save(self, device, event_time=T1, lat=6.9271, lon=79.8612, speed=23.0, heading=90.0):
        return await self.ts.save_location(device, lat, lon, speed, heading, 12, event_time)

    async def count(self, table, device=None):
        q = f'SELECT count(*) FROM "{table}"' + (' WHERE "DeviceId" = $1' if device else "")
        return await (self.conn.fetchval(q, device) if device else self.conn.fetchval(q))

    async def test_assigned_device_writes_history_and_live_position_in_one_call(self):
        self.assertTrue(await self.save(DEV_ASSIGNED))
        self.assertEqual(await self.count("GpsTrackings", DEV_ASSIGNED), 1)
        row = await self.conn.fetchrow('SELECT * FROM "CurrentLocations" WHERE "DeviceId" = $1', DEV_ASSIGNED)
        self.assertEqual(str(row["VehicleId"]), VEHICLE)
        self.assertTrue(row["IgnitionStatus"])            # taken from DeviceStatuses inside the statement
        self.assertTrue(row["MovementStatus"])            # speed > 0
        self.assertEqual(row["LastUpdate"], T1)

    async def test_unassigned_device_keeps_history_but_gets_no_live_row(self):
        self.assertFalse(await self.save(DEV_UNASSIGNED))
        self.assertEqual(await self.count("GpsTrackings", DEV_UNASSIGNED), 1)
        self.assertEqual(await self.count("CurrentLocations", DEV_UNASSIGNED), 0)

    async def test_second_position_updates_the_live_row_and_adds_history(self):
        await self.save(DEV_ASSIGNED, T1, lat=6.98024)
        await self.save(DEV_ASSIGNED, T2, lat=6.98115, speed=0.0)
        self.assertEqual(await self.count("GpsTrackings", DEV_ASSIGNED), 2)
        self.assertEqual(await self.count("CurrentLocations", DEV_ASSIGNED), 1)
        row = await self.conn.fetchrow('SELECT * FROM "CurrentLocations" WHERE "DeviceId" = $1', DEV_ASSIGNED)
        self.assertEqual(float(row["Latitude"]), 6.98115)
        self.assertFalse(row["MovementStatus"])           # speed 0
        self.assertEqual(row["LastUpdate"], T2)

    async def test_ignition_defaults_to_false_without_a_status_row(self):
        await self.save(DEV_NO_STATUS)
        row = await self.conn.fetchrow('SELECT * FROM "CurrentLocations" WHERE "DeviceId" = $1', DEV_NO_STATUS)
        self.assertEqual(str(row["VehicleId"]), VEHICLE_2)
        self.assertFalse(row["IgnitionStatus"])

    async def test_floats_are_stored_short_not_as_50_digit_numerics(self):
        # 2026-10-10 incident: raw float binding produced numerics C# decimal cannot read.
        await self.save(DEV_ASSIGNED, lat=7.025998333333333, lon=79.89795555555555)
        lat_text = await self.conn.fetchval('SELECT "Latitude"::text FROM "GpsTrackings" LIMIT 1')
        lon_text = await self.conn.fetchval('SELECT "Longitude"::text FROM "CurrentLocations" LIMIT 1')
        self.assertLessEqual(len(lat_text.split(".")[1]), 6, lat_text)
        self.assertLessEqual(len(lon_text.split(".")[1]), 6, lon_text)

    async def test_duplicate_event_time_creates_a_second_row_when_idempotency_is_off(self):
        # Documents today's behaviour (flag off, no unique index).
        with patch.object(self.ts, "GPS_TRACKING_IDEMPOTENT", False):
            await self.save(DEV_ASSIGNED, T1)
            await self.save(DEV_ASSIGNED, T1)
        self.assertEqual(await self.count("GpsTrackings", DEV_ASSIGNED), 2)

    async def test_duplicate_event_time_is_ignored_when_idempotency_is_on(self):
        await self.conn.execute('DROP INDEX "IX_GpsTrackings_DeviceId_EventTime"')
        await self.conn.execute('CREATE UNIQUE INDEX "IX_GpsTrackings_DeviceId_EventTime" '
                                'ON "GpsTrackings"("DeviceId", "EventTime" DESC)')
        with patch.object(self.ts, "GPS_TRACKING_IDEMPOTENT", True):
            self.assertTrue(await self.save(DEV_ASSIGNED, T1))
            self.assertTrue(await self.save(DEV_ASSIGNED, T1))        # retransmission
            await self.save(DEV_ASSIGNED, T2)
        self.assertEqual(await self.count("GpsTrackings", DEV_ASSIGNED), 2)
        self.assertEqual(await self.count("CurrentLocations", DEV_ASSIGNED), 1)

    async def test_idempotent_mode_without_the_unique_index_fails_loudly(self):
        # Why the flag defaults to false: enabling it before the index exists breaks every write.
        import asyncpg
        with patch.object(self.ts, "GPS_TRACKING_IDEMPOTENT", True):
            with self.assertRaises(asyncpg.PostgresError):
                await self.save(DEV_ASSIGNED)

    # ---- the two GPS103 status upserts (never run against real Postgres before) ----

    async def test_mark_device_alive_first_contact_inserts_neutral_defaults_then_only_refreshes(self):
        await self.ts.mark_device_alive(DEV_UNASSIGNED)                      # no DeviceStatuses row yet
        row = await self.conn.fetchrow('SELECT * FROM "DeviceStatuses" WHERE "DeviceId" = $1', DEV_UNASSIGNED)
        self.assertTrue(row["IsOnline"])
        self.assertEqual((row["BatteryLevel"], row["GpsSignal"], row["PowerStatus"]), (0, 0, 0))
        self.assertIsNone(row["LastHeartbeat"])

        await self.conn.execute(
            'UPDATE "DeviceStatuses" SET "BatteryLevel" = 5, "GpsSignal" = 3 WHERE "DeviceId" = $1', DEV_UNASSIGNED)
        await self.ts.mark_device_alive(DEV_UNASSIGNED, heartbeat=True)      # must NOT overwrite battery/signal
        row = await self.conn.fetchrow('SELECT * FROM "DeviceStatuses" WHERE "DeviceId" = $1', DEV_UNASSIGNED)
        self.assertEqual((row["BatteryLevel"], row["GpsSignal"]), (5, 3))
        self.assertIsNotNone(row["LastHeartbeat"])
        self.assertEqual(await self.count("DeviceStatuses", DEV_UNASSIGNED), 1)

    async def test_set_ignition_inserts_then_updates_a_single_row(self):
        await self.ts.set_ignition(DEV_UNASSIGNED, True)
        await self.ts.set_ignition(DEV_UNASSIGNED, False)
        rows = await self.conn.fetch('SELECT "IgnitionStatus" FROM "DeviceStatuses" WHERE "DeviceId" = $1', DEV_UNASSIGNED)
        self.assertEqual([r["IgnitionStatus"] for r in rows], [False])


if __name__ == "__main__":
    unittest.main()
